#!/usr/bin/env python3
"""Builds Lamb Stampede for release.

Usage: python3 tools/build.py [out_dir]

1. Regenerates js/licences.js (the engine's MIT notice and the font licence).
2. Writes sw.js with the list of files to keep offline and a build stamp, so every
   release reaches players as "Update ready, tap to refresh".
3. Writes into out_dir (default ../dist):
   - lamb-stampede-<version>.zip: the whole site, ready to upload
   - lamb-stampede-<version>-single.html: the whole game in one file, font and all
"""
import base64
import hashlib
import json
import pathlib
import re
import sys
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / "dist"
OUT.mkdir(parents=True, exist_ok=True)
VERSION = re.search(r'version:\s*"([^"]+)"', (ROOT / "js/config.js").read_text()).group(1)
SKIP = {"tools", "dist"}
SKIP_FILES = {"sw.js"}


def site_files():
    for p in sorted(ROOT.rglob("*")):
        rel = p.relative_to(ROOT)
        if p.is_dir() or rel.parts[0] in SKIP or p.name.startswith("."):
            continue
        yield rel


# ---- 1. licences ----
def licences():
    ofl = (ROOT / "fonts/OFL.txt").read_text().strip()
    head = (ROOT / "js/engine.js").read_text().split("const Engine")[0]
    lines = [l[3:] if l.startswith("// ") else l[2:] for l in head.strip().splitlines()]
    start = next(k for k, l in enumerate(lines) if l.startswith("Written for"))
    mit = "\n".join(lines[start:]).strip()
    body = json.dumps({"engine": mit, "font": ofl}, indent=1, ensure_ascii=False)
    (ROOT / "js/licences.js").write_text(
        "// ============================== LICENCES ==============================\n"
        "// Shown on the About screen. Generated by tools/build.py from fonts/OFL.txt and js/engine.js.\n"
        f"var LICENCES = {body};\n")


# ---- 2. the service worker ----
SW = """// ============================== SERVICE WORKER ==============================
// Generated by tools/build.py. Keeps the game playable offline. A new release changes the
// build stamp below, the browser installs the new files quietly, and the game offers
// "Update ready, tap to refresh" when the player isn't in the middle of a game.
const BUILD = "%(build)s";
const CACHE = "lamb-stampede-" + BUILD;
const FILES = %(files)s;

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES.map((f) => new Request(f, { cache: "reload" })))));
});

self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("lamb-stampede-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});

self.addEventListener("message", (e) => {
  if (e.data === "skipWaiting") self.skipWaiting();
});

// cache first (it's all ours and versioned by BUILD); pages fall back to the game when offline
self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET" || new URL(req.url).origin !== location.origin) return;
  e.respondWith(
    caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req).catch(() => (req.mode === "navigate" ? caches.match("./") : Response.error())))
  );
});
"""


def service_worker():
    files = ["./"] + [str(r).replace("\\", "/") for r in site_files() if r.name not in SKIP_FILES and r.suffix not in {".md"} and r.name not in {"_headers", "vercel.json", "robots.txt", "404.html"}]
    h = hashlib.sha256()
    for f in files[1:]:
        h.update(f.encode())
        h.update((ROOT / f).read_bytes())
    build = f"{VERSION}-{h.hexdigest()[:10]}"
    (ROOT / "sw.js").write_text(SW % {"build": build, "files": json.dumps(files, indent=1)})
    return build


# ---- 3a. the single-file build ----
def single_file():
    html = (ROOT / "index.html").read_text()
    css = (ROOT / "css/app.css").read_text()
    font = base64.b64encode((ROOT / "fonts/fredoka.woff2").read_bytes()).decode()
    css = css.replace('url("../fonts/fredoka.woff2")', f'url("data:font/woff2;base64,{font}")')
    html = html.replace('<link rel="stylesheet" href="css/app.css">', f"<style>\n{css}\n</style>")
    html = re.sub(r'<link rel="preload"[^>]*>\n', "", html)
    html = re.sub(r'<link rel="manifest"[^>]*>\n', "", html)
    fav = base64.b64encode((ROOT / "icons/favicon.png").read_bytes()).decode()
    html = re.sub(r'<link rel="icon"[^>]*>', f'<link rel="icon" href="data:image/png;base64,{fav}" type="image/png">', html)
    html = re.sub(r'<link rel="apple-touch-icon"[^>]*>\n', "", html)

    def inline(m):
        return f"<script>\n{(ROOT / m.group(1)).read_text()}\n</script>"

    html = html.replace('<script src="js/config.js"></script>', '<script>window.SINGLE_FILE = true;</script>\n<script src="js/config.js"></script>')
    html = re.sub(r'<script src="(js/[^"]+)"></script>', inline, html)
    # every mode goes in too, before the game starts
    modes = "".join(f"<script>\n{p.read_text()}\n</script>\n" for p in sorted((ROOT / "js/modes").glob("*.js")))
    html = html.replace("<script>\n  try {\n    $(\"pause-btn\")", modes + "<script>\n  try {\n    $(\"pause-btn\")")
    out = OUT / f"lamb-stampede-{VERSION}-single.html"
    out.write_text(html)
    return out


# ---- 3b. the zip ----
def zip_site():
    out = OUT / f"lamb-stampede-{VERSION}.zip"
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for rel in site_files():
            z.write(ROOT / rel, f"lamb-stampede/{rel}")
        for rel in sorted((ROOT / "tools").glob("*")):
            if rel.is_file():
                z.write(rel, f"lamb-stampede/tools/{rel.name}")
    return out


licences()
build = service_worker()
s = single_file()
z = zip_site()
print(f"build {build}")
print(f"{s.name}: {s.stat().st_size // 1024} KB")
print(f"{z.name}: {z.stat().st_size // 1024} KB")
